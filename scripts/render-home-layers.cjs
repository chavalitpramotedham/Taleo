/**
 * Pre-paints the homepage's sample scene into still image layers, so the
 * "painting before your eyes" animation only has to fade finished pictures
 * in (GPU work) instead of re-running the watercolour filters across the
 * whole scene on every frame.
 *
 * Each top-level part of HOME_SCENE (washes, painted shapes, details) is
 * rendered on its own, with the site's real paint filters, to a transparent
 * WebP in public/art/home/. Pen-line parts stay as live SVG (they draw on
 * stroke by stroke), written with the image list to src/lib/art/homeLayers.ts.
 *
 * Re-run after changing HOME_SCENE or the paint filters:
 *   npm run dev            (in another terminal)
 *   node scripts/render-home-layers.cjs [http://localhost:3000]
 * Needs playwright-core and Google Chrome installed.
 */
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright-core");

const BASE = process.argv[2] || "http://localhost:3000";
const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public/art/home");
const W = 880; // 2.2x the 400x300 canvas: sharp on retina at the homepage's size
const H = 660;
const QUALITY = 0.8;

(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await page.goto(BASE, { waitUntil: "load" });
  await page.waitForSelector(".hero-paint-canvas svg");

  // The shared paint filters, and the scene's top-level parts as rendered.
  const { defs, parts } = await page.evaluate(() => {
    const defsSvg = document.querySelector("#tl-wash").closest("svg");
    const scene = document.querySelector(".hero-paint-canvas svg");
    const holder = scene.querySelector(":scope > g");
    const parts = Array.from(holder.children)
      .filter((el) => el.tagName.toLowerCase() === "g")
      .map((g) => {
        const filter = g.getAttribute("filter") || "";
        const kind = filter.includes("tl-wash") ? "wash" : filter.includes("tl-paint") ? "paint" : filter.includes("tl-ink") ? "ink" : "detail";
        const clone = g.cloneNode(true);
        clone.removeAttribute("class");
        clone.removeAttribute("style");
        if (kind === "ink") clone.querySelectorAll("*").forEach((p) => p.setAttribute("pathLength", "1"));
        return { kind, markup: clone.outerHTML };
      });
    return { defs: defsSvg.outerHTML, parts };
  });

  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const f of fs.readdirSync(OUT_DIR)) if (f.startsWith("layer-")) fs.unlinkSync(path.join(OUT_DIR, f));

  const layers = [];
  const shot = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  for (let i = 0; i < parts.length; i++) {
    const { kind, markup } = parts[i];
    if (kind === "ink") {
      layers.push({ kind, svg: markup });
      continue;
    }
    await shot.setContent(
      `<!doctype html><html><head><style>html,body{margin:0;background:transparent}svg{display:block}</style></head><body>${defs}` +
        `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width="${W}" height="${H}">${markup}</svg></body></html>`,
    );
    const png = await shot.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: W, height: H } });
    // PNG -> WebP (with alpha) using the browser's own encoder.
    const webp = await shot.evaluate(
      async ({ b64, q }) => {
        const img = new Image();
        img.src = `data:image/png;base64,${b64}`;
        await img.decode();
        const c = document.createElement("canvas");
        c.width = img.width;
        c.height = img.height;
        c.getContext("2d").drawImage(img, 0, 0);
        return c.toDataURL("image/webp", q).split(",")[1];
      },
      { b64: png.toString("base64"), q: QUALITY },
    );
    const name = `layer-${String(i).padStart(2, "0")}.webp`;
    fs.writeFileSync(path.join(OUT_DIR, name), Buffer.from(webp, "base64"));
    layers.push({ kind, src: `/art/home/${name}` });
    console.log(name, kind, Math.round(Buffer.from(webp, "base64").length / 1024) + "KB");
  }
  await browser.close();

  const ts =
    `// Generated by scripts/render-home-layers.cjs from HOME_SCENE - don't edit by hand.\n` +
    `// The homepage painting's parts in paint order: pre-painted images, and\n` +
    `// pen lines kept as live SVG so they can draw on.\n` +
    `export type HomeLayer = { kind: "wash" | "paint" | "detail"; src: string } | { kind: "ink"; svg: string };\n\n` +
    `export const HOME_LAYERS: HomeLayer[] = ${JSON.stringify(layers, null, 2)};\n`;
  fs.writeFileSync(path.join(ROOT, "src/lib/art/homeLayers.ts"), ts);
  console.log(`wrote ${layers.length} layers`);
})();
